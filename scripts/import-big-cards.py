"""Import the separate ID workbook without changing the master or legacy catalogs."""
import hashlib
import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    if len(sys.argv) != 2:
        raise SystemExit('Usage: npm run import:big-cards -- <技能ID对照表.xlsx>')
    source = Path(sys.argv[1]).resolve()
    spec = importlib.util.spec_from_file_location('xlsx_reader', ROOT / 'scripts/import-skills.py')
    reader = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(reader)
    cards = {}
    for row_number, row in reader.read_sheet(source, '卡牌ID对照'):
        if not row or not re.fullmatch(r'[12]\d{4}', row[0]):
            continue
        card_id = row[0]
        if card_id in cards:
            raise ValueError(f'Duplicate card ID: {card_id}')
        if row[4] != card_id[1:3]:
            raise ValueError(f'Grade mismatch: {card_id}')
        cards[card_id] = {
            'id': card_id, 'name': row[1], 'kind': 'native' if card_id[0] == '1' else 'fusion',
            'rankCode': row[4], 'sourceGroup': row[6], 'attribute': row[7],
            'sourceRow': int(row[9]), 'abilities': [], '_childCount': int(row[8]),
        }
    if not cards:
        raise ValueError('Missing card ID sheet or empty card catalog')
    child_ids = set()
    for row_number, row in reader.read_sheet(source, '子技能ID对照'):
        if not row or not re.fullmatch(r'[12]\d{6}', row[0]):
            continue
        child_id, parent_id, parent_name, order, description, source_cell = row[:6]
        card = cards.get(parent_id)
        if not card or parent_name != card['name'] or child_id != parent_id + f'{int(order):02d}':
            raise ValueError(f'Invalid child relationship: row {row_number}')
        if child_id in child_ids or not description.strip():
            raise ValueError(f'Duplicate or empty child: {child_id}')
        child_ids.add(child_id)
        ability = {'id': child_id, 'order': int(order), 'description': description, 'sourceCell': source_cell}
        if len(row) > 6 and row[6].strip():
            ability['implementedRules'] = row[6]
        card['abilities'].append(ability)
    for card in cards.values():
        card['abilities'].sort(key=lambda item: item['order'])
        if len(card['abilities']) != card.pop('_childCount') or [a['order'] for a in card['abilities']] != list(range(1, len(card['abilities']) + 1)):
            raise ValueError(f'Missing or noncontiguous children: {card["id"]}')
    output = ROOT / 'packages/shared/src/bigCards/generatedCatalog.ts'
    payload = json.dumps(list(cards.values()), ensure_ascii=False, indent=2)
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    output.write_text('import type { BigCardCatalogEntry } from "./types";\n\n'
        f'// Generated by scripts/import-big-cards.py from {source.name}; do not edit manually.\n'
        f'// Source SHA-256: {digest}\n'
        f'export const RAW_BIG_CARD_CATALOG: BigCardCatalogEntry[] = {payload};\n', encoding='utf-8', newline='\n')
    print(f'Imported {len(cards)} cards and {len(child_ids)} abilities -> {output}')


if __name__ == '__main__':
    main()
